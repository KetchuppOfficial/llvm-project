#define DEBUG_TYPE "mc-code-emitter"
STATISTIC(MCNumEmitted, "The number of emitted MC instruction");

#define GET_INSTRINFO_ENUM
#include "DAArch34GenInstrInfo.inc"

namespace llvm {

class MCOperand;
class MCInst;
class MCInstrInfo;

namespace {

class DAArch34MCCodeEmitter : public MCCodeEmitter {
public:
  DAArch34MCCodeEmitter(MCContext &Ctx) : Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override {
    const auto Bits = (getBinaryCodeForInstr(MI, Fixups, STI));
    support::endian::write<uint32_t>(CB, Bits, endianness::little);
    ++MCNumEmitted;
  }

  int64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const {
    if (MO.isReg()) {
      return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
    } else if (MO.isImm()) {
      return MO.getImm();
    }

    assert(MO.isExpr());

    if (int64_t Res; MO.getExpr()->evaluateAsAbsolute(Res)) {
      return Res;
    }

    llvm_unreachable(
        "DAArch34MCCodeEmitter::getMachineOpValue: unhandled expression");
  }

  int64_t getSImm16OpValue(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    const MCOperand &MO = MI.getOperand(OpNo);
    if (MO.isImm()) {
      return MO.getImm();
    }

    assert(MO.isExpr() && "DAArch34MCCodeEmitter::getSImm16OpValue expects "
                          "only expressions or an immediate");

    if (const auto *CE = dyn_cast<MCConstantExpr>(MO.getExpr())) {
      return CE->getValue();
    }
    return 0;
  }

private:
  // generated by tablegen
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  MCContext &Ctx;
};

#include "DAArch34GenMCCodeEmitter.inc"

} // end unnamed namespace

MCCodeEmitter *createDAArch34MCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx) {
  return new DAArch34MCCodeEmitter(Ctx);
}

} // end namespace llvm
