#include "llvm/MC/MCRegister.h"
#include "llvm/Support/raw_ostream.h"

#include "MCTargetDesc/DAArch34InstPrinter.h"

#define DEBUG_TYPE "inst-printer"

namespace llvm {

class MCAsmInfo;
class MCInstrInfo;
class MCRegisterInfo;
class MCSubtargetInfo;

namespace {

class DAArch34InstPrinter : public MCInstPrinter {
public:
  DAArch34InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                      const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  /// Returns a pair containing the mnemonic for \p MI and the number of bits
  /// left for further processing by printInstruction (generated by tablegen).
  std::pair<const char *, uint64_t> getMnemonic(const MCInst *MI) override;

  /// Print the assembler register name.
  void printRegName(raw_ostream &O, MCRegister Reg) const override {
    O << getRegisterName(Reg);
  }

  /// Print the specified MCInst to the specified raw_ostream.
  ///
  /// \p Address the address of current instruction on most targets, used to
  /// print a PC relative immediate as the target address. On targets where a PC
  /// relative immediate is relative to the next instruction and the length of a
  /// MCInst is difficult to measure (e.g. x86), this is the address of the next
  /// instruction. If Address is 0, the immediate will be printed.
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override {
    printInstruction(MI, Address, O);
    printAnnotation(O, Annot);
  }

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O) {
    if (const MCOperand &MO = MI->getOperand(OpNo); MO.isReg()) {
      printRegName(O, MO.getReg());
    } else if (MO.isImm()) {
      O << MO.getImm();
    } else {
      assert(MO.isExpr() && "Unknown operand kind in printOperand");
      MO.getExpr()->print(O, &MAI);
    }
  }

  void printBranchOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                          raw_ostream &O) {
    const MCOperand &MO = MI->getOperand(OpNo);
    if (MO.isImm()) {
      return printOperand(MI, OpNo, O);
    } else if (PrintBranchImmAsAddress) {
      O << formatHex(static_cast<uint64_t>(Address + MO.getImm()));
    } else {
      O << MO.getImm();
    }
  }

  // generated by tablegen
  static const char *getRegisterName(MCRegister Reg);

  // generated by tablegen
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
};

#include "DAArch34GenAsmWriter.inc"

} // end unnamed namespace

MCInstPrinter *createDAArch34MCInstPrinter(const Triple &TT,
                                           unsigned SyntaxVariant,
                                           const MCAsmInfo &MAI,
                                           const MCInstrInfo &MII,
                                           const MCRegisterInfo &MRI) {
  return new DAArch34InstPrinter(MAI, MII, MRI);
}

} // end namespace llvm
